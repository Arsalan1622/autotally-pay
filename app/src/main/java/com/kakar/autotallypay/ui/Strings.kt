    /** Render a ViewModel notice in this language. */
    fun noticeText(notice: Notice): String {
        val amount = notice.amountPaisa?.let { Money.formatRupees(it) } ?: ""
        return when (notice.key) {
            "paymentRecorded" -> "$paymentRecorded — $amount (${notice.customerName ?: ""})"
            "paymentRecordedUnmatched" -> "$paymentRecordedUnmatched — $amount"
            "fakeSmsFlagged" -> fakeSmsFlagged
            "alreadyRecorded" -> alreadyRecorded
            "notAPaymentSms" -> notAPaymentSms
            "assigned" -> "$assigned (${notice.customerName ?: ""})"
            "billAdded" -> billAdded
            "customerAdded" -> customerAdded
            else -> notice.key
        }
    }
}

